  await page.getByLabel('Target width').fill('1280');
  await page.getByLabel('Target height').fill('720');

  await page.getByRole('button', { name: 'Assets', exact: true }).click();
  await expect.poll(() => page.locator('.asset-icon').first().evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
