  await installFolderPicker(page, [`import-${crypto.randomUUID()}`]);
  await page.goto(baseURL);
  await expect(page.getByRole('status')).toContainText('Project checks passed.');
  for (const name of ['Project', 'Assets', 'Scenes']) await expect(page.getByRole('button', { name, exact: true })).toBeEnabled();
  for (const name of ['Characters', 'Items', 'Game Map']) await expect(page.getByRole('button', { name: new RegExp(name) })).toBeDisabled();
