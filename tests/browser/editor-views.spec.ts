  await page.getByRole('button', { name: 'dock.png' }).click();
  await page.getByRole('button', { name: 'dock.png' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Delete' }).click();
  await expect(page.getByRole('alert')).toContainText('used by a scene');
  await page.getByRole('button', { name: /sounds/ }).click();
