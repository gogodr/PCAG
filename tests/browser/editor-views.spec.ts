  await expect(page.getByRole('button', { name: 'pier.png' })).toBeVisible();
  await page.getByRole('button', { name: 'pier.png' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Rename' }).click();
  await page.getByLabel('File or folder name').fill('dock.png');
  await page.getByLabel('File or folder name').press('Enter');
  await expect(page.getByRole('button', { name: 'dock.png' })).toBeVisible();
  await page.getByRole('navigation', { name: 'Asset path' }).getByRole('button', { name: 'backgrounds' }).click();
  await page.getByRole('region', { name: 'Folder contents' }).getByRole('button', { name: 'harbor' }).click({ button: 'right' });
  await page.getByRole('menuitem', { name: 'Rename' }).click();
  await page.getByLabel('File or folder name').fill('waterfront');
  await page.getByLabel('File or folder name').press('Enter');
  await expect(page.getByRole('button', { name: /waterfront/ })).toBeVisible();

  await page.getByRole('button', { name: 'Scenes', exact: true }).click();
  await expect.poll(() => page.locator('.scene-tree-icon').first().evaluate(element => (element as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: testInfo.outputPath('scene-icons.png'), fullPage: true });
  await expect(page.locator('.topbar').getByLabel('Select scene')).toBeVisible();
  await expect(page.getByRole('tree', { name: 'Scene element tree' }).getByRole('treeitem', { name: 'Background' })).toBeVisible();
  await expect(page.getByRole('complementary', { name: 'Inspector' }).getByLabel('Scene background')).toBeVisible();
  await page.getByRole('button', { name: 'Add scene' }).click();
  await expect(page.getByLabel('Scene name')).toHaveValue('New Scene');
  await expect(page.getByLabel('Scene name')).toBeFocused();
  expect(await page.getByLabel('Scene name').evaluate(input => (input as HTMLInputElement).selectionEnd)).toBe('New Scene'.length);
  await page.getByLabel('Scene name').fill('Harbor');
  await page.getByLabel('Scene name').press('Enter');
  await expect(page.getByLabel('Select scene').locator('option:checked')).toHaveText('Harbor');
  await page.getByRole('button', { name: 'Rename scene' }).click();
  await expect(page.getByLabel('Scene name')).toHaveValue('Harbor');
  await page.getByLabel('Scene name').fill('Harbor dusk');
  await page.getByLabel('Scene name').press('Enter');
  await expect(page.getByLabel('Select scene').locator('option:checked')).toHaveText('Harbor dusk');
  await page.getByLabel('Scene background').selectOption({ label: 'dock.png' });
